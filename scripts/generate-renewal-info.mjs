#!/usr/bin/env node
/**
 * One dataset, two consumers.
 *
 * landing/states/states-data.json is the researched renewal-logistics record
 * (board, portal, fee, cycle, deadline, steps, pitfalls, sources). The
 * marketing pages render it; the APP needs the same facts wherever it tells
 * a physician something is due, because a warning without the door to fix it
 * is homework, not help.
 *
 * Emits src/constants/renewalInfo.js (keyed by state abbreviation) and
 * supabase/functions/send-reminders/renewalLinks.json (slim: portal/board
 * URL per state for the email digest). Re-run whenever the research updates.
 */
import { readFileSync, writeFileSync } from "node:fs";

const { states } = JSON.parse(readFileSync("landing/states/states-data.json", "utf8"));
const clean = (v) => (v && !String(v).includes("RESEARCH NEEDED") ? v : null);

const byAbbr = {};
for (const s of states) {
  byAbbr[s.abbreviation] = {
    name: s.name,
    board: clean(s.boardName),
    boardUrl: clean(s.boardUrl),
    portalUrl: clean(s.portalUrl) || clean(s.boardUrl),
    doBoard: clean(s.doBoardName) || null,
    doBoardUrl: clean(s.doBoardUrl) || null,
    cycle: clean(s.renewalCycle),
    due: clean(s.renewalAnchor) || clean(s.renewalMonth),
    fee: clean(s.renewalFee),
    lateFee: clean(s.lateFee) || null,
    processing: clean(s.processingTime),
    lapse: clean(s.graceOrLapse) || null,
    steps: (s.steps || []).filter(x => !String(x).includes("RESEARCH NEEDED")),
    guideUrl: `https://credentialdomd.com/states/${s.slug}`,
  };
}

const banner = `// GENERATED by scripts/generate-renewal-info.mjs from landing/states/states-data.json.\n// Do not edit by hand; update the data file and re-run.\n`;
writeFileSync("src/constants/renewalInfo.js", banner + "export const RENEWAL_INFO = " + JSON.stringify(byAbbr, null, 1) + ";\n");

const slim = Object.fromEntries(Object.entries(byAbbr).map(([k, v]) => [k, { portal: v.portalUrl, board: v.board, due: v.due, guide: v.guideUrl }]));
writeFileSync("supabase/functions/send-reminders/renewalLinks.json", JSON.stringify(slim, null, 1) + "\n");
console.log(`renewalInfo.js: ${Object.keys(byAbbr).length} states, ${Object.values(byAbbr).filter(v => v.fee).length} with a verified fee`);
