#!/usr/bin/env node
// Generates the PA and NP rule modules from data/app-rules (DESIGN 2.1 to 2.5).
//
//   data/app-rules/ledger/<ST>.json, ledger/national.json   evidence: every fact with
//                                                           cite, url, quote, verified
//   data/app-rules/ledger/additions/<ST>.json               facts verified later (optional)
//   data/app-rules/states/<ST>.json, national.json          canonical, every number
//                                                           names the fact it comes from
//        |  node scripts/generate-app-rules.mjs            validates, then writes
//        |  node scripts/generate-app-rules.mjs --check    exit 1 if a file is stale
//        v
//   src/constants/paStateRules.js, npStateRules.js, certificationRules.js
//   supabase/functions/send-reminders/appBoardLinks.json
//   data/app-rules/coverage.json
//
// The owner's rule is the generator's rule: a number reaches the app only
// through a fact that is verified, loaded, has an https URL and a quote, and
// whose value or quote states the number (or the canonical entry gives a
// reason a person reviewed). Anything else becomes "not yet verified" with
// the board link. Incomplete curation degrades to unverified, never to a
// guess, and never to physician numbers.
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { STATE_NAMES } from "../src/constants/states.js";
import { getCmeTopics } from "../src/constants/cmeTopics.js";
import { getCMECategories } from "../src/constants/credentialTypes.js";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA = path.join(ROOT, "data/app-rules");
const read = (p) => JSON.parse(readFileSync(p, "utf8"));
const BANNER = (from) => `// GENERATED by scripts/generate-app-rules.mjs from ${from}. Do not edit.\n// Change the data and run: node scripts/generate-app-rules.mjs\n`;

const https = (value) => {
  try {
    const u = new URL(value);
    return u.protocol === "https:" && !u.username && !u.password ? u.href : null;
  } catch { return null; }
};
const hostOf = (url) => { try { return new URL(url).host.replace(/^www\./i, "").toLowerCase(); } catch { return ""; } };

/** A fact may support a number: verified, loaded, https, quoted. */
export function factUsable(f) {
  return !!f && f.verified === true && f.loaded !== false && !!https(f.url) && typeof f.quote === "string" && f.quote.trim().length > 0;
}

const WORDS = { 1: ["annual", "annually", "one", "every year", "12 months", "12-month"], 2: ["biennial", "biennially", "two", "24 months", "24-month", "two-year", "two year"], 3: ["triennial", "triennially", "three", "36 months", "36-month"], 4: ["four"], 5: ["five"], 6: ["six"], 10: ["ten"] };

/** Whether a fact states a number, as a numeral or its word form. */
export function factStatesNumber(fact, n) {
  const text = `${JSON.stringify(fact?.value ?? "")} ${fact?.quote || ""}`.toLowerCase();
  const plain = String(n);
  const withComma = Number(n).toLocaleString("en-US");
  const numeral = new RegExp(`(^|[^0-9.])(${plain.replace(".", "\\.")}|${withComma.replace(".", "\\.")})([^0-9]|$)`);
  if (numeral.test(text)) return true;
  // "four thousand hours", "three hundred clock hours"
  const UNITS = ["", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"];
  for (const [size, word] of [[1000, "thousand"], [100, "hundred"]]) {
    if (n >= size && n % size === 0 && n / size <= 10 && text.includes(`${UNITS[n / size]} ${word}`)) return true;
  }
  return (WORDS[n] || []).some((w) => text.includes(w));
}

/**
 * Every figure in a piece of text (a topic label, a note, an option, an
 * agreement summary) is stated by one of its facts, so prose cannot carry a
 * number the evidence does not. Returns the first figure no fact states, or null.
 */
export function unstatedFigure(text, facts) {
  for (const m of String(text || "").matchAll(/\d[\d,]*(?:\.\d+)?/g)) {
    const n = Number(m[0].replace(/,/g, ""));
    if (!Number.isFinite(n)) continue;
    if (!facts.some((f) => f && factStatesNumber(f, n))) return m[0];
  }
  return null;
}

/** Facts per state, indexed by field, from the ledger and additions. */
function loadStateFacts(st) {
  const ledger = read(path.join(DATA, "ledger", `${st}.json`));
  const additions = existsSync(path.join(DATA, "ledger/additions", `${st}.json`)) ? read(path.join(DATA, "ledger/additions", `${st}.json`)) : [];
  const byProfession = { pa: new Map(), np: new Map() };
  const add = (prof, f) => {
    if (!f?.field) return;
    const list = byProfession[prof].get(f.field) || [];
    list.push(f);
    byProfession[prof].set(f.field, list);
  };
  for (const f of ledger.pa?.facts || []) add("pa", f);
  for (const f of ledger.np?.facts || []) add("np", f);
  for (const f of Array.isArray(additions) ? additions : additions.facts || []) add(f.profession === "pa" || f.profession === "np" ? f.profession : String(f.field).startsWith("np.") ? "np" : "pa", f);
  return { ledger, byProfession };
}

/** The first usable fact for a field id, or null. */
function usableFact(index, id) {
  // "field#2" names the second fact recorded under a field id (the research
  // reused a few ids for different facts).
  const m = /^(.*)#(\d+)$/.exec(id || "");
  if (m) return [(index.get(m[1]) || [])[Number(m[2]) - 1]].find(factUsable) || null;
  return (index.get(id) || []).find(factUsable) || null;
}

/**
 * Resolve one canonical scalar { value, fact } or { value, facts, reason }.
 * Returns { ok: true, value, cite, url, facts } or { ok: false, why }.
 */
export function resolveScalar(spec, index, { needsNumber = true } = {}) {
  if (!spec || typeof spec !== "object" || !("value" in spec)) return { ok: false, why: "no value" };
  const ids = spec.facts || (spec.fact ? [spec.fact] : []);
  if (!ids.length) return { ok: false, why: "no fact" };
  const facts = ids.map((id) => usableFact(index, id));
  if (facts.some((f) => !f)) return { ok: false, why: `fact not verified: ${ids.filter((id, i) => !facts[i]).join(", ")}` };
  if (needsNumber && typeof spec.value === "number" && spec.value !== 0 && !spec.reason && !facts.some((f) => factStatesNumber(f, spec.value))) {
    return { ok: false, why: `no fact states ${spec.value}` };
  }
  if (typeof spec.value === "string" && /\bTODO\b/.test(spec.value)) return { ok: false, why: "TODO" };
  return { ok: true, value: spec.value, cite: facts[0].cite || "", url: https(facts[0].url), facts: ids };
}

const KIND_NOUN = { pa: "physician assistant license", rn: "RN license", aprn: "APRN license" };

/** A board URL is used only when its host appears among that state's verified fact URLs. */
function boardFor(canonBoard, index) {
  const name = typeof canonBoard?.name === "string" && canonBoard.name.trim() ? canonBoard.name.trim() : null;
  const url = https(canonBoard?.url);
  const hosts = new Set([...index.values()].flat().filter(factUsable).map((f) => hostOf(f.url)));
  return { board: name, boardUrl: url && hosts.has(hostOf(url)) ? url : null };
}

function stub({ profession, kind, st, board, boardUrl, why }) {
  return {
    profession, kind, state: st, board, boardUrl,
    licenseTitle: null,
    status: "unverified", ceMode: "unverified", windowRule: "unverified",
    cycle: null, total: null, unit: kind === "pa" ? "hours" : "contact hours",
    cat1min: null, cat1note: "", cat1Accepted: [], cat1Unverified: [],
    totalAccepted: null, totalUnverified: null,
    certificationInLieu: null, certificationRequired: null, practiceHours: null, satisfiesRn: false, nlc: null,
    licenseCycle: null,
    topics: [], notes: [],
    source: board || "Not yet verified", sourceUrl: boardUrl || "",
    verified: null,
    unverified: [{ item: `Continuing education rules for the ${STATE_NAMES[st] || st} ${KIND_NOUN[kind]}`, boardUrl, why: why || "not curated yet" }],
    practice: null, prescribing: null,
    facts: {},
  };
}

/** One kind's rule set (pa, rn or aprn) from its canonical section. */
function buildKind({ profession, kind, st, section, index, board, boardUrl, verifiedAt }) {
  if (!section?.ce) return stub({ profession, kind, st, board, boardUrl });
  const out = stub({ profession, kind, st, board, boardUrl });
  out.unverified = [];
  // statedBy: the facts that state every figure in the item (an open item
  // may say what IS verified: Arkansas, at least 5 hours, frequency open).
  const miss = (item, why, statedBy) => out.unverified.push({ item, boardUrl, why, ...(statedBy ? { statedBy } : {}) });
  const ce = section.ce;
  validateSection(section, profession, `${st} ${kind}`);
  // The license's own name (Oregon, Maine and Iowa say "physician associate").
  // A label, not a rule: a plain string, or { value, fact }.
  const rawTitle = section.license?.title;
  const title = typeof rawTitle === "string" ? { ok: !!rawTitle.trim(), value: rawTitle.trim() } : resolveScalar(rawTitle, index, { needsNumber: false });
  out.licenseTitle = title.ok ? title.value : null;
  // How often the license itself renews, which can differ from the CE
  // counting cycle (Minnesota PA: annual license, CE over two years).
  if (section.license?.cycleYears) {
    const lc = resolveScalar(section.license.cycleYears, index);
    out.licenseCycle = lc.ok ? lc.value : null;
    if (lc.ok) out.facts.licenseCycle = lc.facts;
  }

  const cycle = resolveScalar(ce.cycleYears, index);
  const total = resolveScalar(ce.total, index);
  let mode = ce.mode || "unverified";
  if (mode === "hours") {
    if (!total.ok || !cycle.ok) {
      mode = "unverified";
      miss("Continuing education hours and how often they are due", [total.why, cycle.why].filter(Boolean).join("; "));
    } else {
      out.cycle = cycle.value; out.total = total.value;
      out.facts.total = total.facts; out.facts.cycle = cycle.facts;
      out.source = total.cite; out.sourceUrl = total.url || out.sourceUrl;
      out.cycleCite = cycle.cite; out.cycleUrl = cycle.url;
    }
  } else if (mode === "none") {
    const none = resolveScalar(ce.none || ce.total, index, { needsNumber: false });
    if (none.ok && (ce.total ? ce.total.value === 0 : true)) {
      out.total = 0; out.facts.total = none.facts; out.source = none.cite; out.sourceUrl = none.url || out.sourceUrl;
      if (cycle.ok) out.cycle = cycle.value;
    } else { mode = "unverified"; miss("Whether a general continuing education requirement applies", none.why); }
  } else if (mode === "certification") {
    const req = resolveScalar(section.certificationRequired, index, { needsNumber: false });
    if (!(req.ok && req.value === true)) { mode = "unverified"; miss("Whether keeping national certification current satisfies renewal", req.why); }
    else {
      if (cycle.ok) out.cycle = cycle.value;
      // The rule the card cites is the certification requirement itself.
      out.source = req.cite || out.source; out.sourceUrl = req.url || out.sourceUrl;
    }
  } else if (mode === "options") {
    const options = (ce.options || []).map((o) => ({ o, ids: o.facts || [o.fact], r: resolveScalar({ value: o.text, facts: o.facts || [o.fact] }, index, { needsNumber: false }) }));
    for (const { o, ids, r } of options) {
      const figure = r.ok && unstatedFigure(o.text, ids.map((id) => usableFact(index, id)));
      if (figure) throw new Error(`${st} ${kind} option "${o.text}": ${figure} is not stated by ${ids.join(", ")}`);
    }
    if (!options.length || options.some((x) => !x.r.ok)) { mode = "unverified"; miss("The continuing education options this board offers", "options not verified"); }
    else {
      out.options = options.map(({ o, r }) => ({ text: o.text, cite: r.cite, url: r.url }));
      if (cycle.ok) out.cycle = cycle.value;
      out.source = options[0].r.cite || out.source; out.sourceUrl = options[0].r.url || out.sourceUrl;
    }
  } else {
    mode = "unverified";
    // The CE rules are open, but the license's renewal cycle may be settled
    // (New York: triennial registration): its window still counts the
    // verified topics (the three-year prescriber training, the four-year
    // infection control course).
    if (ce.mode === "unverified" && ce.cycleYears && cycle.ok) { out.cycle = cycle.value; out.facts.cycle = cycle.facts; }
    // A curated "unverified" section names what is missing in its own list.
    if (!(section.unverified || []).length) miss(`Continuing education rules for the ${STATE_NAMES[st] || st} ${KIND_NOUN[kind]}`, ce.mode === "unverified" ? "not verified" : "mode not curated");
  }
  out.ceMode = mode;

  // Counting window: the licence rule unless a fact and a reason say otherwise.
  if (mode === "unverified" && !(ce.mode === "unverified" && out.cycle && !ce.windowRule)) out.windowRule = "unverified";
  else if (mode === "unverified") out.windowRule = "license";
  else if (ce.windowRule === "calendarYears") {
    const w = resolveScalar(ce.window, index, { needsNumber: false });
    out.windowRule = w.ok && ce.window?.reason ? "calendarYears" : "unverified";
    if (out.windowRule === "calendarYears" && ce.window?.preceding === true) out.windowPreceding = true;
    if (out.windowRule === "unverified") miss("Which dates count toward the hours", w.why || "no reason given");
  } else if (ce.windowRule === "fixed") {
    // Fixed periods from a stated start (Alabama PA: "Effective January 1,
    // 2025, every two calendar years"; Mississippi PA: "the two-year period
    // begins July 1, 2022"): the period holding the renewal date is counted.
    const w = resolveScalar(ce.window, index, { needsNumber: false });
    const anchor = ce.window?.anchor;
    const year = /^(\d{4})-\d{2}-\d{2}$/.exec(anchor || "")?.[1];
    const stated = w.ok && year && w.facts.map((id) => usableFact(index, id)).some((f) => factStatesNumber(f, Number(year)));
    if (stated && ce.window?.reason && out.cycle) { out.windowRule = "fixed"; out.windowAnchor = anchor; }
    else { out.windowRule = "unverified"; miss("Which dates count toward the hours", w.why || (!stated ? "no fact states the period's start" : "no reason given")); }
  } else if (ce.windowRule === "memberStart") {
    // The period starts on a date only the member's own record shows (North
    // Carolina PA: the birthday after the license was issued): the member
    // sets CME Cycle Start, and the period runs the cycle from there.
    const w = resolveScalar(ce.window, index, { needsNumber: false });
    out.windowRule = w.ok && ce.window?.reason && out.cycle ? "memberStart" : "unverified";
    if (out.windowRule === "unverified") miss("Which dates count toward the hours", w.why || "no reason given");
  } else if (ce.windowRule === "unverified") {
    // The hours are verified but the dates they count over are not (Alabama:
    // "every two calendar years" on an annual licence). No bar is computed
    // until the member sets a CME Cycle Start.
    out.windowRule = "unverified";
    miss("Which dates count toward the hours", "counting period not verified");
  } else out.windowRule = out.cycle ? "license" : "unverified";

  if (ce.categoryMin) {
    const min = resolveScalar(ce.categoryMin, index);
    if (min.ok) {
      out.cat1min = min.value; out.cat1note = ce.categoryMin.label || ""; out.cat1Cite = min.cite; out.cat1Url = min.url;
      out.cat1Accepted = [...(ce.categoryMin.accepted || [])];
      out.cat1Unverified = [...(ce.categoryMin.unverifiedAccepted || [])];
      out.facts.cat1min = min.facts;
    } else miss(ce.categoryMin.label ? `Minimum hours of ${ce.categoryMin.label}` : "Category minimum", min.why);
  }
  if (ce.totalAccepted) {
    // Which categories count toward the total is a rule like any other: it
    // names the fact that says so, or the list is dropped (every accredited
    // category then counts and Other / Non-accredited CE only "may count").
    const r = resolveScalar(ce.totalAccepted, index, { needsNumber: false });
    if (r.ok) { out.totalAccepted = [...r.value]; out.facts.totalAccepted = r.facts; }
    else miss("Which kinds of credit count toward the total", r.why);
  }
  if (Array.isArray(ce.totalUnverifiedAccepted)) out.totalUnverified = [...ce.totalUnverifiedAccepted];

  if (ce.certificationInLieu) {
    const c = ce.certificationInLieu;
    const r = resolveScalar({ value: true, fact: c.fact }, index, { needsNumber: false });
    if (r.ok) {
      out.certificationInLieu = {
        // The bodies are verified when a fact names them (bodiesFact,
        // North Carolina 21 NCAC 36 .0801(8)); otherwise only when the
        // in-lieu fact itself does (bodiesVerified false says it does not).
        bodies: [...(c.bodies || [])], bodiesVerified: c.bodiesFact ? !!usableFact(index, c.bodiesFact) : c.bodiesVerified !== false, covers: [...(c.covers || ["total"])],
        notForTopics: [...(c.notForTopics || [])], note: c.note || "", cite: r.cite, url: r.url,
      };
    } else miss("Whether national certification satisfies the hours", r.why);
  }
  if (ce.satisfiesRn) {
    const r = resolveScalar(ce.satisfiesRn, index, { needsNumber: false });
    out.satisfiesRn = r.ok && r.value === true;
  }
  if (section.certificationRequired) {
    const r = resolveScalar(section.certificationRequired, index, { needsNumber: false });
    // A condition limits who must hold it (Colorado: APRNs with prescriptive authority).
    const cond = section.certificationRequired.condition || null;
    out.certificationRequired = r.ok ? { value: r.value === true, cite: r.cite, url: r.url, ...(cond ? { condition: cond } : {}) } : null;
    if (!r.ok) miss("Whether current national certification is required", r.why);
  }
  if (section.practiceHours) {
    const p = section.practiceHours;
    // The hours come from the first fact; a label naming alternatives cites
    // the facts that state them (Arizona: a degree within five years).
    const ids = p.facts || [p.fact];
    const r = resolveScalar({ value: p.hours, facts: ids, reason: p.reason }, index);
    const labelFacts = ids.map((id) => usableFact(index, id));
    if (r.ok && p.label && unstatedFigure(p.label, labelFacts)) throw new Error(`${st} ${kind} practice hours label "${p.label}": ${unstatedFigure(p.label, labelFacts)} is not stated by ${ids.join(", ")}`);
    if (r.ok) out.practiceHours = { hours: p.hours, years: p.years, ...(p.label ? { label: p.label } : {}), cite: r.cite, url: r.url };
    else miss("Practice hours required for renewal", r.why);
  }
  if (section.nlc) {
    const r = resolveScalar(section.nlc, index, { needsNumber: false });
    out.nlc = r.ok ? { value: r.value === true, effectiveThrough: section.nlc.effectiveThrough || null, cite: r.cite, url: r.url } : null;
  }
  // A renewal the hours are not due for (a first renewal, a new licensee):
  // the member answers the question on the licence for this renewal, and a
  // Yes waives the hours (and the topics listed). Unanswered, the hours stand.
  if (ce.exemption) {
    const e = ce.exemption;
    const ids = e.facts || [e.fact];
    if (!(typeof e.field === "string" && e.field && typeof e.question === "string" && e.question && typeof e.text === "string" && e.text)) throw new Error(`${st} ${kind} exemption needs field, question and text`);
    const r = resolveScalar({ value: e.text, facts: ids }, index, { needsNumber: false });
    const exFacts = ids.map((id) => usableFact(index, id));
    for (const words of [e.text, e.question]) {
      if (r.ok && unstatedFigure(words, exFacts)) throw new Error(`${st} ${kind} exemption "${words}": ${unstatedFigure(words, exFacts)} is not stated by ${ids.join(", ")}`);
    }
    // whenAnswer "No" reads the question the other way (Hawaii APRN: the 30
    // hours are for APRNs renewing prescriptive authority); perRenewal false
    // keeps a standing answer (prescriptive authority) instead of one per renewal.
    if (r.ok) out.exemption = { field: e.field, question: e.question, text: e.text, topics: e.topics === "all" ? "all" : [...(e.topics || [])],
      whenAnswer: e.whenAnswer === "No" ? "No" : "Yes", perRenewal: e.perRenewal !== false, cite: r.cite, url: r.url };
    else miss("Who is exempt from the hours at a renewal", r.why);
  }
  for (const n of ce.notes || []) {
    const ids = n.facts || [n.fact];
    const r = resolveScalar({ value: n.text, facts: ids }, index, { needsNumber: false });
    const noteFacts = ids.map((id) => usableFact(index, id));
    if (r.ok && unstatedFigure(n.text, noteFacts)) throw new Error(`${st} ${kind} note "${n.text}": ${unstatedFigure(n.text, noteFacts)} is not stated by ${ids.join(", ")}`);
    if (r.ok) out.notes.push({ text: n.text, cite: r.cite, url: r.url });
  }
  for (const t of section.topics || []) {
    validateTopic(t, profession, `${st} ${kind}`);
    out.topics.push(buildTopic(t, index, boardUrl, miss));
  }
  for (const item of section.unverified || []) miss(item, "listed as not yet verified");

  out.verified = verifiedAt || null;
  out.status = out.ceMode === "unverified" ? "unverified" : out.unverified.length || out.topics.some((t) => t.status === "unverified") ? "partial" : "verified";
  return out;
}

/**
 * A topic's period is a rule too (periods encoded, DESIGN 7.4): every renewal
 * (no period), one time ("lifetime"), or every N years. A one-time or N-year
 * period must be stated by the topic's own fact (one time / once / initial /
 * first; N as a numeral, word or months) or carry a periodReason a person
 * reviewed. Returns why it is not stated, or null.
 */
export function periodProblem(t, facts) {
  const p = t.period;
  if (p == null) return null;
  if (t.periodReason) return null;
  // "had not completed the one-time course" describes an earlier course, not
  // this one (California PA Schedule II, BPC 3502.1(e)(3)): it states no period.
  const text = facts.map((f) => `${JSON.stringify(f?.value ?? "")} ${f?.quote || ""}`).join(" ").toLowerCase()
    .replace(/completed\s+(?:the|a|an)\s+(?:earlier\s+)?one[- ]time\b[^.;"]*/g, " ");
  if (p === "lifetime") return /one[- ]time|\bonce\b|\binitial|\bfirst\b|single|prior to|\bbefore\b|within .* of (the )?(initial|licen|employ|registr|commenc)/.test(text) ? null : "no fact says it is one time";
  if (typeof p === "object" && p.years > 0) {
    // A period on fixed due dates (New York: "by July 1, 2017, and once every
    // three years thereafter") names its first due date in a fact too.
    if (p.anchor && !facts.some((f) => factStatesNumber(f, Number(String(p.anchor).slice(0, 4))))) return "no fact states the first due date";
    if (p.years === 1 && /\b(each|every|per|a) year\b|\byearly\b|\bannual/.test(text)) return null;
    return facts.some((f) => factStatesNumber(f, p.years) || factStatesNumber(f, p.years * 12)) ? null : `no fact states every ${p.years} years`;
  }
  return "period is not every renewal, one time or every N years";
}

const MODES = new Set(["hours", "certification", "none", "options", "unverified"]);
const WINDOWS = new Set([undefined, "license", "calendarYears", "fixed", "memberStart", "unverified"]);

/** Structural checks on a curated section; a failure stops the generator. */
export function validateSection(section, profession, where) {
  const ce = section.ce;
  const problems = [];
  if (!MODES.has(ce.mode)) problems.push(`ce.mode "${ce.mode}"`);
  if (!WINDOWS.has(ce.windowRule)) problems.push(`ce.windowRule "${ce.windowRule}"`);
  const cats = getCMECategories(profession === "pa" ? "PA" : "NP");
  const lists = [ce.totalAccepted?.value, ce.totalUnverifiedAccepted, ce.categoryMin?.accepted, ce.categoryMin?.unverifiedAccepted];
  for (const list of lists) for (const c of list || []) if (!cats.includes(c)) problems.push(`category "${c}" is not a ${profession.toUpperCase()} category`);
  if (ce.totalAccepted && !Array.isArray(ce.totalAccepted.value)) problems.push("ce.totalAccepted is { value: [...], fact }");
  for (const n of ce.notes || []) if (!n.fact && !n.facts) problems.push(`note without a fact: ${n.text}`);
  if (problems.length) throw new Error(`${where}: ${problems.join("; ")}`);
}

/** Structural checks a curated file must pass; a failure stops the generator. */
export function validateTopic(t, profession, where) {
  const topics = getCmeTopics(profession === "pa" ? "PA" : "NP");
  const problems = [];
  if (!topics.includes(t.topic)) problems.push(`topic "${t.topic}" is not in getCmeTopics`);
  for (const x of t.alsoTopics || []) if (!topics.includes(x)) problems.push(`alsoTopics "${x}" is not in getCmeTopics`);
  if (t.condition && !(typeof t.condition.field === "string" && t.condition.field && typeof t.condition.question === "string" && t.condition.question)) problems.push("condition needs field and question");
  if (t.period != null && t.period !== "lifetime" && !(typeof t.period === "object" && Number.isInteger(t.period.years) && t.period.years > 0)) problems.push("period must be absent, \"lifetime\" or { years: N }");
  if (typeof t.period === "object" && t.period && t.period.fromToday != null && t.period.fromToday !== true) problems.push("period.fromToday is true or absent");
  if (typeof t.period === "object" && t.period?.anchor != null && !/^\d{4}-\d{2}-\d{2}$/.test(String(t.period.anchor))) problems.push("period.anchor is YYYY-MM-DD");
  if (t.status !== "unverified" && !(t.fact || t.facts)) problems.push("a verified topic names its fact");
  if (t.status !== "unverified" && !(typeof t.hours === "number" && t.hours >= 0)) problems.push("a verified topic has hours (0 = a course with no stated hours)");
  for (const k of ["expiringOnOrAfter", "expiringBefore"]) if (t[k] && !/^\d{4}-\d{2}-\d{2}$/.test(t[k])) problems.push(`${k} is YYYY-MM-DD`);
  const cats = getCMECategories(profession === "pa" ? "PA" : "NP");
  for (const c of t.acceptedCategories || []) if (!cats.includes(c)) problems.push(`category "${c}" is not a ${profession.toUpperCase()} category`);
  if (problems.length) throw new Error(`${where} ${t.topic}: ${problems.join("; ")}`);
}

function buildTopic(t, index, boardUrl, miss) {
  const base = {
    topic: t.topic, alsoTopics: Array.isArray(t.alsoTopics) && t.alsoTopics.length ? [...t.alsoTopics] : null, note: t.label || t.topic, condition: t.condition || null,
    period: t.period || null, acceptedCategories: t.acceptedCategories || null,
    measure: t.measure || null, additional: t.additional === true, separate: t.separate === true,
    expiringOnOrAfter: t.expiringOnOrAfter || null, expiringBefore: t.expiringBefore || null,
    notCoveredByCertification: t.notCoveredByCertification === true,
    // Verified on the hours route but not when renewing by certification
    // (California PA geriatric share): the item shown on the certification route.
    unverifiedUnderCertification: t.unverifiedUnderCertification ? String(t.unverifiedUnderCertification) : null,
  };
  if (t.status === "unverified") {
    // An open item may state what IS verified (Arkansas: at least 5 pain
    // management hours, frequency open); its figures must be its facts'.
    const ids = t.facts || (t.fact ? [t.fact] : []);
    if (ids.length) {
      const fs = ids.map((id) => usableFact(index, id));
      if (fs.some((f) => !f)) throw new Error(`topic ${t.topic}: unverified item cites a fact that is not verified (${ids.join(", ")})`);
      const fig = unstatedFigure(t.unverifiedItem, fs);
      if (fig) throw new Error(`topic ${t.topic} item "${t.unverifiedItem}": ${fig} is not stated by ${ids.join(", ")}`);
    }
    miss(t.unverifiedItem || `${t.topic} requirement`, "topic not verified", ids.length ? ids : undefined);
    return { ...base, hours: null, status: "unverified", unverifiedItem: t.unverifiedItem || `${t.topic} requirement`, cite: "", url: boardUrl || "" };
  }
  const r = resolveScalar({ value: t.hours, fact: t.fact, facts: t.facts, reason: t.reason }, index, { needsNumber: t.hours > 0 });
  if (!r.ok) {
    miss(`${t.topic} requirement`, r.why);
    return { ...base, hours: null, status: "unverified", unverifiedItem: `${t.topic} requirement`, cite: "", url: boardUrl || "" };
  }
  const figure = unstatedFigure(t.label, r.facts.map((id) => usableFact(index, id)));
  if (figure) throw new Error(`topic ${t.topic} label "${t.label}": ${figure} is not stated by ${r.facts.join(", ")}`);
  const why = periodProblem(t, r.facts.map((id) => usableFact(index, id)));
  if (why) {
    miss(`How often the ${t.topic} requirement is due`, why);
    return { ...base, hours: null, status: "unverified", unverifiedItem: `How often the ${t.topic} requirement is due`, cite: "", url: boardUrl || "" };
  }
  const cov = t.coveredByCertification ? resolveScalar({ value: true, fact: t.coveredByCertification.fact }, index, { needsNumber: false }) : null;
  return { ...base, hours: t.hours, status: "verified", cite: r.cite, url: r.url, coveredByCertification: !!cov?.ok };
}

function sectionShared(sec, index, miss) {
  const out = { practice: null, prescribing: null };
  const a = sec?.practice?.agreement;
  if (a) {
    const cites = (a.facts || []).map((id) => usableFact(index, id));
    if (cites.length && cites.every(Boolean) && unstatedFigure(a.text, cites)) throw new Error(`agreement "${a.text}": ${unstatedFigure(a.text, cites)} is not stated by ${a.facts.join(", ")}`);
    if (cites.length && cites.every(Boolean)) {
      out.practice = { agreement: { kind: a.kind || "", text: a.text || "", conditional: a.conditional === true, cites: cites.map((f) => ({ cite: f.cite, url: https(f.url) })) } };
    } else miss("Practice agreement rules", "agreement facts not verified");
  }
  const cs = sec?.prescribing?.stateCsRegistration;
  if (cs) {
    const r = resolveScalar(cs, index, { needsNumber: false });
    out.prescribing = r.ok ? { stateCsRegistration: { value: r.value === true, cite: r.cite, url: r.url } } : null;
  }
  return out;
}

/**
 * One state's PA set, NP sets, board links and coverage from a canonical
 * object (the file in data/app-rules/states, or a draft under test).
 */
export function buildState(st, canon) {
  const { byProfession } = loadStateFacts(st);
  const verifiedAt = canon.verifiedAt || null;

  const paBoard = boardFor(canon.pa?.board, byProfession.pa);
  const paSet = buildKind({ profession: "pa", kind: "pa", st, section: canon.pa, index: byProfession.pa, ...paBoard, verifiedAt });
  const paShared = sectionShared(canon.pa, byProfession.pa, (item, why) => paSet.unverified.push({ item, boardUrl: paBoard.boardUrl, why }));
  paSet.practice = paShared.practice; paSet.prescribing = paShared.prescribing;

  const npBoard = boardFor(canon.np?.board, byProfession.np);
  const rn = buildKind({ profession: "np", kind: "rn", st, section: canon.np?.rn, index: byProfession.np, ...npBoard, verifiedAt });
  const aprn = buildKind({ profession: "np", kind: "aprn", st, section: canon.np?.aprn, index: byProfession.np, ...npBoard, verifiedAt });
  const unverified = [];
  const npShared = sectionShared(canon.np, byProfession.np, (item, why) => unverified.push({ item, boardUrl: npBoard.boardUrl, why }));
  for (const item of canon.np?.unverified || []) unverified.push({ item, boardUrl: npBoard.boardUrl, why: "listed as not yet verified" });
  const npState = { state: st, ...npBoard, rn, aprn, practice: npShared.practice, prescribing: npShared.prescribing, unverified };

  const links = { pa: { board: paBoard.board, url: paBoard.boardUrl }, np: { board: npBoard.board, url: npBoard.boardUrl } };
  // Dated items: rules that start, end or are due to change on a known day,
  // so the owner can schedule a recheck (DESIGN 8.2 step 4).
  const dated = (sec, r) => [
    ...((sec?.dated || []).map((d) => ({ date: d.date, item: d.item }))),
    ...r.topics.filter((t) => t.expiringOnOrAfter).map((t) => ({ date: t.expiringOnOrAfter, item: `${t.topic} starts for licenses expiring on or after this date` })),
    ...r.topics.filter((t) => t.expiringBefore).map((t) => ({ date: t.expiringBefore, item: `${t.topic} ends for licenses expiring on or after this date` })),
    ...(r.nlc?.effectiveThrough ? [{ date: r.nlc.effectiveThrough, item: "Nurse Licensure Compact membership ends unless extended" }] : []),
  ].sort((a, b) => a.date.localeCompare(b.date));
  const cov = (sec, r) => ({ status: r.status, ceMode: r.ceMode, unverified: r.unverified.map((u) => u.item), dated: dated(sec, r) });
  const coverage = { pa: cov(canon.pa, paSet), rn: cov(canon.np?.rn, rn), aprn: cov(canon.np?.aprn, aprn), boardUrls: { pa: paBoard.boardUrl, np: npBoard.boardUrl } };
  return { pa: paSet, np: npState, links, coverage };
}

export function buildStates() {
  const pa = {}, np = {}, links = {}, coverage = {};
  const files = readdirSync(path.join(DATA, "states")).filter((f) => f.endsWith(".json")).sort();
  for (const file of files) {
    const st = file.slice(0, -5);
    const built = buildState(st, read(path.join(DATA, "states", file)));
    pa[st] = built.pa; np[st] = built.np; links[st] = built.links; coverage[st] = built.coverage;
  }
  return { pa, np, links, coverage };
}

export function buildNational() {
  const ledger = read(path.join(DATA, "ledger/national.json"));
  const index = new Map();
  for (const f of ledger.facts || []) index.set(f.field, [...(index.get(f.field) || []), f]);
  const canon = read(path.join(DATA, "national.json"));
  const rules = {}, coverage = {}, sources = new Map();
  const META = new Set(["profession", "name", "fullName", "unit", "unverified", "mayCount"]);
  for (const [body, spec] of Object.entries(canon.bodies)) {
    const out = { body, profession: spec.profession, name: spec.name, fullName: spec.fullName, unit: spec.unit || "hours", url: null, unverified: [] };
    for (const [key, field] of Object.entries(spec)) {
      if (META.has(key)) continue;
      const r = resolveScalar(field, index, { needsNumber: true });
      if (key === "url") { out.url = r.ok && https(r.value) ? r.value : null; continue; }
      if (r.ok) {
        out[key] = r.value;
        out.cites = out.cites || {};
        out.cites[key] = { cite: r.cite, url: r.url };
        if (r.url) sources.set(r.url, { name: spec.fullName, url: r.url, cite: r.cite });
      } else {
        out[key] = null;
        out.unverified.push({ item: field?.unverifiedItem || `${spec.name}: ${key}`, why: r.why });
      }
    }
    out.mayCount = Array.isArray(spec.mayCount?.value) ? [...spec.mayCount.value] : [];
    for (const item of spec.unverified || []) out.unverified.push({ item, why: "listed as not yet verified" });
    out.status = out.unverified.length ? (Object.keys(out.cites || {}).length ? "partial" : "unverified") : "verified";
    rules[body] = out;
    coverage[body] = { status: out.status, unverified: out.unverified.map((u) => u.item) };
  }
  const dea = {};
  for (const [key, field] of Object.entries(canon.dea || {})) {
    const r = resolveScalar(field, index);
    dea[key] = r.ok ? r.value : null;
    if (r.ok && r.url) sources.set(r.url, { name: "DEA Diversion Control Division", url: r.url, cite: r.cite });
  }
  return { rules, dea, coverage, sources: [...sources.values()].sort((a, b) => a.url.localeCompare(b.url)), verifiedAt: canon.verifiedAt };
}

const jsModule = (from, exportsList) => BANNER(from) + exportsList.map(([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 1)};\n`).join("");

export function generate() {
  const { pa, np, links, coverage } = buildStates();
  const national = buildNational();
  const meta = { generatedFrom: "data/app-rules", researchedAt: "2026-10", ledgerVerifiedAt: "2026-10-01" };
  return {
    "src/constants/paStateRules.js": jsModule("data/app-rules/states", [["PA_STATE_RULES_META", meta], ["PA_STATE_RULES", pa]]),
    "src/constants/npStateRules.js": jsModule("data/app-rules/states", [["NP_STATE_RULES_META", meta], ["NP_STATE_RULES", np]]),
    "src/constants/certificationRules.js": jsModule("data/app-rules/national.json", [
      ["CERTIFICATION_RULES_META", { generatedFrom: "data/app-rules/national.json", verifiedAt: national.verifiedAt }],
      ["CERTIFICATION_RULES", national.rules], ["DEA_APP_RULES", national.dea], ["APP_GENERAL_SOURCES", national.sources],
    ]),
    "supabase/functions/send-reminders/appBoardLinks.json": JSON.stringify(links, null, 1) + "\n",
    "data/app-rules/coverage.json": JSON.stringify({ states: coverage, national: national.coverage }, null, 1) + "\n",
  };
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith("generate-app-rules.mjs")) {
  const check = process.argv.includes("--check");
  const files = generate();
  const stale = [];
  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(ROOT, rel);
    const current = existsSync(abs) ? readFileSync(abs, "utf8") : null;
    if (current === content) continue;
    if (check) { stale.push(rel); continue; }
    mkdirSync(path.dirname(abs), { recursive: true });
    writeFileSync(abs, content);
    console.log(`wrote ${rel}`);
  }
  if (check && stale.length) {
    console.error(`Stale generated files (run node scripts/generate-app-rules.mjs):\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
  if (!check) {
    const cov = JSON.parse(files["data/app-rules/coverage.json"]);
    const count = (k) => Object.values(cov.states).filter((s) => s[k].status !== "unverified").length;
    console.log(`PA rule sets with verified data: ${count("pa")}/51; RN ${count("rn")}/51; APRN ${count("aprn")}/51.`);
    console.log(`National: ${Object.entries(cov.national).map(([b, c]) => `${b} ${c.status}`).join(", ")}.`);
  }
}
