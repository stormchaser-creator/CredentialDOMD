#!/usr/bin/env node
// Copy the app modules the edge functions share into supabase/functions/_shared/app/.
//
// The email-inbound function files a forwarded document with the same prompt,
// validator, category rules and identifier gate the app uses, and
// send-invoice-email sends the invoice email the app previews. A Supabase edge
// function is bundled from supabase/functions/ and cannot import from src/, so
// those modules are copied, not forked: each copy is its source verbatim under
// a generated banner, at the same path relative to src/ (src/utils/x.js ->
// _shared/app/utils/x.js), so every relative import inside it still resolves.
//
// Run after changing any of the sources:
//   node scripts/sync-shared-app-modules.mjs          write the copies
//   node scripts/sync-shared-app-modules.mjs --check  exit 1 if any copy drifted
// scripts/shared-app-modules.test.mjs runs the check as part of npm test.
//
// Every import inside a copied module must be a relative path WITH its
// extension ("./scanDates.js", not "./scanDates"): Deno resolves nothing
// else. The planner refuses to copy a module that breaks that rule, and it
// follows imports, so a new dependency is copied (and checked) too.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, rmSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const SOURCE_DIR = "src";
export const TARGET_DIR = "supabase/functions/_shared/app";

// The modules the edge functions import directly. Their imports are followed.
export const ROOTS = Object.freeze([
  "utils/scannerCore.js",
  "utils/customCategories.js",
  "utils/sectionFields.js",
  "utils/scanSplit.js",
  "utils/phiGuard.js",
  "utils/geminiModel.js",
  // send-invoice-email composes the message with the same code the app
  // previews it with, and finds an invoice's receipts with the app's rule.
  "utils/invoiceEmail.js",
  "utils/receiptFiles.js",
]);

export const banner = (rel) =>
  `// GENERATED by scripts/sync-shared-app-modules.mjs from ${SOURCE_DIR}/${rel}. Do not edit.\n` +
  `// Change the source and run: node scripts/sync-shared-app-modules.mjs\n` +
  `// scripts/shared-app-modules.test.mjs fails when this copy drifts from its source.\n`;

/** Every module specifier a file imports or re-exports, including dynamic imports. */
export function importsOf(source) {
  const out = [];
  const statics = /^\s*(?:import|export)\s+(?:[^'";]*?\s+from\s+)?["']([^"']+)["']/gm;
  let m;
  while ((m = statics.exec(source))) out.push(m[1]);
  const dynamic = /\bimport\s*\(\s*["']([^"']+)["']\s*\)/g;
  while ((m = dynamic.exec(source))) out.push(m[1]);
  return out;
}

/** Why a specifier cannot be used inside a copied module, or "". */
export function specifierProblem(spec) {
  if (!spec.startsWith("./") && !spec.startsWith("../")) return `"${spec}" is not a relative path`;
  if (!/\.m?js$/.test(spec)) return `"${spec}" has no .js extension`;
  return "";
}

/**
 * The copies to write: [{ rel, source, target, content }], following imports
 * from ROOTS. Throws on an import that is not relative-and-extensionful, or
 * that leaves src/.
 */
export function planCopies(root = REPO_ROOT) {
  const srcRoot = path.join(root, SOURCE_DIR);
  const seen = new Map();
  const visit = (rel) => {
    if (seen.has(rel)) return;
    const file = path.join(srcRoot, rel);
    if (!existsSync(file)) throw new Error(`${SOURCE_DIR}/${rel} does not exist`);
    const text = readFileSync(file, "utf8");
    seen.set(rel, text);
    for (const spec of importsOf(text)) {
      const why = specifierProblem(spec);
      if (why) throw new Error(`${SOURCE_DIR}/${rel}: ${why}. Shared modules need relative imports with the extension.`);
      const next = path.posix.normalize(path.posix.join(path.posix.dirname(rel), spec));
      if (next.startsWith("../")) throw new Error(`${SOURCE_DIR}/${rel}: "${spec}" leaves ${SOURCE_DIR}/`);
      visit(next);
    }
  };
  for (const r of ROOTS) visit(r);
  return [...seen.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([rel, text]) => ({
    rel,
    source: `${SOURCE_DIR}/${rel}`,
    target: `${TARGET_DIR}/${rel}`,
    content: banner(rel) + text,
  }));
}

/** Every .js file currently under the target directory, relative to it. */
export function existingCopies(root = REPO_ROOT) {
  const base = path.join(root, TARGET_DIR);
  const out = [];
  const walk = (dir) => {
    if (!existsSync(dir)) return;
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith(".js")) out.push(path.relative(base, p).split(path.sep).join("/"));
    }
  };
  walk(base);
  return out.sort();
}

/** Human-readable drift, [] when every copy matches its source and nothing extra is there. */
export function driftProblems(root = REPO_ROOT) {
  const problems = [];
  const plan = planCopies(root);
  const wanted = new Set(plan.map((p) => p.rel));
  for (const p of plan) {
    const file = path.join(root, p.target);
    if (!existsSync(file)) { problems.push(`${p.target} is missing`); continue; }
    if (readFileSync(file, "utf8") !== p.content) problems.push(`${p.target} differs from ${p.source}`);
  }
  for (const rel of existingCopies(root)) {
    if (!wanted.has(rel)) problems.push(`${TARGET_DIR}/${rel} has no source in the copy set`);
  }
  return problems;
}

export function writeCopies(root = REPO_ROOT) {
  const plan = planCopies(root);
  const wanted = new Set(plan.map((p) => p.rel));
  for (const p of plan) {
    const file = path.join(root, p.target);
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, p.content);
  }
  for (const rel of existingCopies(root)) {
    if (!wanted.has(rel)) rmSync(path.join(root, TARGET_DIR, rel));
  }
  return plan;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes("--check")) {
    const problems = driftProblems();
    if (problems.length) {
      console.error(`Shared app modules drifted:\n  ${problems.join("\n  ")}\nRun: node scripts/sync-shared-app-modules.mjs`);
      process.exit(1);
    }
    console.log("Shared app modules match their sources.");
  } else {
    const plan = writeCopies();
    console.log(`Wrote ${plan.length} shared app modules:\n  ${plan.map((p) => p.target).join("\n  ")}`);
  }
}
