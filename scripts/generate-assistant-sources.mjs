// Copies provenance, not a new rule review. No clock-derived verification dates.
import { readFileSync, writeFileSync } from 'node:fs';
const stateData = JSON.parse(readFileSync('landing/states/states-data.json', 'utf8'));
const cme = JSON.parse(readFileSync('public/knowledge/credentialdo-cme.json', 'utf8'));
const data = {
  reviewScope: cme.reviewScope,
  generalSources: cme.sources.map(({ id, title, url, checkedOn }) => ({ id, title, url, recordedReview: checkedOn || null })),
  renewalSources: Object.fromEntries(stateData.states.map(s => [s.abbreviation, {
    recordedReview: s.verified || null,
    sources: (s.sources || []).map(s => ({ url: s.url })),
  }])),
};
const output = '// GENERATED by scripts/generate-assistant-sources.mjs. Dates are copied source metadata, not a live check.\n'
  + `export const ASSISTANT_SOURCES = ${JSON.stringify(data, null, 2)};\n`;
const target = 'src/constants/assistantSources.js';
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Assistant sources are stale; regenerate from the source datasets.');
} else writeFileSync(target, output);
