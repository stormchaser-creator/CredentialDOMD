import test from "node:test";
import assert from "node:assert/strict";
import { buildInvoicePdf } from "../../src/utils/invoicePdf.js";
import { invoiceDocumentArgs } from "../../src/utils/invoiceArgs.js";

const invoice = {
  number: "INV-QA-CONTACT", sentAt: "2026-10-01T12:00:00Z",
  periodStart: "2026-09-30", periodEnd: "2026-09-30",
  totalAmount: 240, totalMinutes: 60, terms: "Synthetic net 30 terms",
  lines: [{ type: "Consult", description: "Synthetic consult", date: "2026-09-30", billedMin: 60, amount: 240 }],
};
const agreement = { facility: "QA Hospital", billTo: "payer@qa.credentialdomd.test" };
const settings = { name: "QA Physician", degreeType: "DO", email: "physician@qa.credentialdomd.test" };
const args = () => invoiceDocumentArgs(invoice, agreement, settings);

// Inspect the real PDF content streams, including line advances, instead of
// matching implementation source or replacing jsPDF with a call recorder.
function inspect(inv) {
  const doc = buildInvoicePdf(inv), H = doc.internal.pageSize.getHeight(), pt = 72 / 25.4;
  const raw = Buffer.from(doc.output("arraybuffer")).toString("latin1");
  const pages = raw.split("endstream").map(chunk => {
    let x = 0, y = 0, leading = 0, size = 9, font = "F1";
    const runs = [];
    for (let line of chunk.split("\n")) {
      let m;
      if ((m = line.match(/^([\d.-]+) ([\d.-]+) Td$/))) { x = Number(m[1]) / pt; y = H - Number(m[2]) / pt; }
      if ((m = line.match(/^([\d.-]+) TL$/))) leading = Number(m[1]) / pt;
      if ((m = line.match(/^\/(F\d+) ([\d.]+) Tf$/))) { font = m[1]; size = Number(m[2]); }
      if (line === "T*" || line.startsWith("T* ")) { y += leading; line = line.slice(2).trimStart(); }
      if ((m = line.match(/^\((.*)\) Tj$/))) runs.push({ text: m[1].replace(/\\([()\\])/g, "$1"), x, y, size, font });
    }
    return runs;
  }).filter(runs => runs.length);
  return { doc, H, W: doc.internal.pageSize.getWidth(), pages, text: pages.flat().map(r => r.text).join("\n") };
}

test("PDF invoice questions go to the physician, while the payer stays in BILL TO", () => {
  const result = inspect(args());
  assert.match(result.text, /Questions about this invoice: QA Physician, DO \(physician@qa\.credentialdomd\.test\)/);
  assert.equal(result.text.split(agreement.billTo).length - 1, 1, "payer is named only in BILL TO");
  assert.doesNotMatch(result.text, /Please remit|Questions about this invoice: payer@/);
});

test("PDF omits the contact footer without a physician email and never substitutes the payer", () => {
  for (const email of [undefined, null, "", "   "]) {
    const result = inspect({ ...args(), email });
    assert.doesNotMatch(result.text, /Questions about this invoice:|Please remit/);
    assert.equal(result.text.split(agreement.billTo).length - 1, 1);
    assert.match(result.text, /TOTAL DUE/);
  }
});

test("PDF long physician and payer contact fields wrap inside their own columns and page", () => {
  const email = `${"a".repeat(60)}@${"b".repeat(60)}.${"c".repeat(60)}.example.test`;
  const billTo = `${"p".repeat(60)}@${"q".repeat(60)}.${"r".repeat(60)}.example.test`;
  const result = inspect({ ...args(), email, billTo,
    physician: "Synthetic Physician With Several Professional Names And Credentials, DO",
    facility: "Synthetic Hospital Department With A Long Billing Office Name" });
  const first = result.pages[0], tableTop = first.find(r => r.text === "Item")?.y;
  assert.ok(tableTop > 47);
  const header = first.filter(r => r.y >= 47 && r.y < tableTop);
  assert.ok(header.length >= 8, "long names and emails actually wrap");
  for (const run of header) {
    result.doc.setFont("helvetica", run.font === "F2" ? "bold" : "normal"); result.doc.setFontSize(run.size);
    const right = run.x < result.W / 2 ? result.W / 2 - 4 : result.W - 16;
    assert.ok(run.x >= 16 - 0.01 && run.x + result.doc.getTextWidth(run.text) <= right + 0.05, `contact column overflow: ${run.text}`);
  }
  const last = result.pages.at(-1), index = last.findIndex(r => r.text.startsWith("Questions about this invoice:"));
  assert.ok(index >= 0);
  const contact = last.slice(index).filter(r => !r.text.startsWith("Generated by") && !r.text.startsWith("Invoice INV-"));
  assert.ok(contact.length >= 2, "long contact footer actually wraps");
  assert.equal(contact.map(r => r.text).join("").replaceAll(" ", ""), `Questionsaboutthisinvoice:SyntheticPhysicianWithSeveralProfessionalNamesAndCredentials,DO(${email})`);
  for (const run of contact) {
    result.doc.setFont("helvetica", "normal"); result.doc.setFontSize(run.size);
    assert.ok(run.x + result.doc.getTextWidth(run.text) <= result.W - 16 + 0.05);
    assert.ok(run.y > 0 && run.y <= result.H - 14, "contact stays above the document footer");
  }
});

test("PDF contact presentation preserves the payer, service date, terms and amount", () => {
  const input = args(), before = structuredClone(input), result = inspect(input);
  for (const value of ["BILL TO", agreement.facility, agreement.billTo, "Service period Sep 30, 2026", "Terms: Synthetic net 30 terms", "TOTAL DUE", "$240.00"]) {
    assert.ok(result.text.includes(value), value);
  }
  assert.deepEqual(input, before, "document rendering does not mutate its inputs");
});
